@competitors_app.command("add")
def competitors_add(
    url: str = typer.Argument(..., help="Channel URL, @handle or channel ID"),
    project: int = typer.Option(..., "--project", "-p", help="Project ID"),
) -> None:
    """Register a competitor channel in a project (backfills if new)."""
    setup_logging()
    from .db import get_database
    from .youtube.client import YouTubeError
    from .worker.channels import register_channel

    settings = get_settings()
    database = get_database(settings)
    try:
        result = register_channel(project, url, settings=settings, database=database)
    except KeyError:
        console.print(f"[red]Project #{project} not found.[/red]")
        raise typer.Exit(code=1)
    except (YouTubeError, ValueError) as exc:
        console.print(f"[red]Could not register the channel:[/red] {exc}")
        raise typer.Exit(code=1)

    if result["existing"]:
        console.print(
            f"[green]Linked[/green] existing channel {result['channel_id']} "
            f"({result['title']}) — no new collection."
        )
    else:
        console.print(
            f"[green]Registered[/green] {result['channel_id']} ({result['title']}); "
            f"backfill queued (rq {result.get('rq_job_id')})."
        )


@competitors_app.command("detach")
def competitors_detach(
    channel_id: str = typer.Argument(..., help="Channel ID (UC...)"),
    project: int = typer.Option(..., "--project", "-p", help="Project ID"),
) -> None:
    """Detach a channel from a project. Keeps all data; deactivates if orphaned."""
    setup_logging()
    from .db import get_database
    from .worker.channels import detach_channel

    settings = get_settings()
    database = get_database(settings)
    try:
        result = detach_channel(project, channel_id, settings=settings, database=database)
    except KeyError:
        console.print(f"[red]Project #{project} not found.[/red]")
        raise typer.Exit(code=1)

    if not result["detached"]:
        console.print(
            f"[yellow]Channel {channel_id} was not linked to project #{project}.[/yellow]"
        )
        return
    tail = " (now orphaned → deactivated)" if result["deactivated"] else ""
    console.print(f"[green]Detached[/green] {channel_id} from project #{project}{tail}.")


@competitors_app.command("list")
def competitors_list(
    project: int = typer.Option(..., "--project", "-p", help="Project ID"),
) -> None:
    """List the channels of a project with their backfill state."""
    setup_logging()
    from .db import competitors as crepo
    from .db import get_database

    settings = get_settings()
    database = get_database(settings)
    with database.session() as s:
        if crepo.get_project(s, project) is None:
            console.print(f"[red]Project #{project} not found.[/red]")
            raise typer.Exit(code=1)
        channels = crepo.list_project_channels(s, project)
        table = Table(title=f"Channels — project #{project}")
        table.add_column("Channel ID", style="bold")
        table.add_column("Title")
        table.add_column("Backfill")
        table.add_column("Active")
        for c in channels:
            state = f"{c.backfill_state} ({c.backfill_done}/{c.backfill_total})"
            table.add_row(c.channel_id, c.title, state, "✅" if c.active else "—")
    console.print(table)


@competitors_app.command("snapshot")
def competitors_snapshot(
    channel: str | None = typer.Option(
        None, "--channel", "-c", help="Limit to a single channel ID (default: all active)"
    ),
    scope: str = typer.Option(
        "all", "--scope", help="Which videos to snapshot: all | recent (< 7 days)"
    ),
) -> None:
    """Run one snapshot cycle inline (manual/testing; no worker/scheduler needed)."""
    setup_logging()
    from .db import get_database
    from .worker.snapshot_jobs import VALID_SCOPES, snapshot_cycle
    from .youtube.client import YouTubeError

    if scope not in VALID_SCOPES:
        console.print(f"[red]Invalid --scope[/red] (use one of {VALID_SCOPES}).")
        raise typer.Exit(code=2)

    settings = get_settings()
    database = get_database(settings)
    try:
        result = snapshot_cycle(
            scope, channel_id=channel, settings=settings, database=database
        )
    except YouTubeError as exc:
        console.print(f"[red]Snapshot failed:[/red] {exc}")
        raise typer.Exit(code=1)

    console.print(
        f"[green]Snapshot ({result['scope']}) done:[/green] "
        f"{result['channels']} channel(s), {result['videos']} video(s), "
        f"{result['packaging_changes']} packaging change(s), "
        f"{result['quota_units']} quota unit(s)."
    )


@metrics_app.command("refresh")
def metrics_refresh() -> None:
    """Persist the derived artifacts (syntactic title attributes + packaging
    impact) without running the scheduler. Idempotent."""
    setup_logging()
    from .db import competitors as crepo
    from .db import get_database
    from .metrics.attributes import refresh_syntactic_attributes
    from .metrics.impact import backfill_packaging_impact

    settings = get_settings()
    database = get_database(settings)
    with database.session() as s:
        video_ids = [
            v.video_id
            for c in crepo.list_active_channels(s)
            for v in crepo.list_channel_videos(s, c.channel_id)
        ]
        attrs = refresh_syntactic_attributes(s, video_ids)
        filled = backfill_packaging_impact(s, settings=settings)
    console.print(
        f"[green]Metrics refreshed:[/green] {attrs} attribute row(s), "
        f"{filled} packaging impact(s) filled."
    )


@metrics_app.command("show")
def metrics_show(
    project: int | None = typer.Option(None, "--project", "-p", help="Project ID"),
    channel: str | None = typer.Option(None, "--channel", "-c", help="Channel ID"),
    video: str | None = typer.Option(None, "--video", "-v", help="Video ID (with --channel)"),
) -> None:
    """Print a dashboard payload (project, channel, or channel+video) as JSON."""
    setup_logging()
    import json

    from .db import get_database
    from .metrics import service

    settings = get_settings()
    database = get_database(settings)
    with database.session() as s:
        if project is not None:
            data = service.project_dashboard(s, project, settings=settings)
        elif channel is not None and video is not None:
            data = service.video_report(s, channel, video, settings=settings)
        elif channel is not None:
            data = service.channel_dashboard(s, channel, settings=settings)
        else:
            console.print("[red]Pass --project, --channel, or --channel + --video.[/red]")
            raise typer.Exit(code=2)

    if data is None:
        console.print("[red]Not found.[/red]")
        raise typer.Exit(code=1)
    console.print_json(json.dumps(data, default=str))



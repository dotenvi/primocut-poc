@app.command()
def doctor() -> None:
    """Validate the environment: GPU/CUDA (WSL2), FFmpeg, yt-dlp and the API key."""
    setup_logging()
    report = doctor_mod.run_diagnostics(get_settings())

    table = Table(title="primocut doctor", show_lines=False)
    table.add_column("Check", style="bold")
    table.add_column("Status")
    table.add_column("Detail", overflow="fold")
    for c in report.checks:
        status = "[green]OK[/green]" if c.ok else "[red]FAILED[/red]"
        table.add_row(c.name, status, c.detail)
    console.print(table)

    failures = [c for c in report.checks if not c.ok]
    if failures:
        console.print("\n[bold yellow]How to fix:[/bold yellow]")
        for c in failures:
            if c.fix:
                console.print(f"  • [bold]{c.name}[/bold]: {c.fix}")
        console.print(
            f"\n[red]{len(failures)} of {len(report.checks)} checks failed.[/red]"
        )
        raise typer.Exit(code=1)

    console.print("\n[green]Environment ready ✔[/green]")


@app.command()
def run(
    url: str = typer.Argument(..., help="YouTube live URL"),
    output: str = typer.Option(
        ".", "-o", "--output",
        help="Output directory for the artifacts (report.md + transcript/topics JSON)",
    ),
    provider: str | None = typer.Option(
        None, "-p", "--provider", help="Analysis provider: anthropic | openai | openrouter"
    ),
    model: str | None = typer.Option(
        None, "-m", "--model", help="Override the model of the selected provider"
    ),
    create_topics: bool = typer.Option(
        False, "--create-topics",
        help="Also extract macro topics with the LLM (extra cost). Off by default.",
    ),
) -> None:
    """Run the pipeline: audio → chat → transcription → report.

    Macro topics are NOT generated by default (they cost an LLM call). Pass
    --create-topics to also run the topic analysis.
    """
    setup_logging()

    from .download.audio import validate_youtube_url

    try:
        url = validate_youtube_url(url)
    except ValueError as exc:
        console.print(f"[red]Invalid URL:[/red] {exc}")
        raise typer.Exit(code=2)

    settings = get_settings()
    if provider:
        settings.llm_provider = provider.lower()
    if model:
        if settings.llm_provider == "openai":
            settings.openai_model = model
        elif settings.llm_provider == "openrouter":
            settings.openrouter_model = model
        else:
            settings.anthropic_model = model

    from .analysis.llm import ToolCallError
    from .pipeline import PipelineError, run_pipeline  # lazy import: heavy deps

    try:
        result = run_pipeline(
            url, output_dir=output, settings=settings, create_topics=create_topics
        )
    except PipelineError as exc:
        console.print(f"[red]Essential stage failed:[/red] {exc}")
        raise typer.Exit(code=1)
    except ToolCallError as exc:
        console.print(f"[red]Analysis failed:[/red] {exc}")
        console.print(
            "[yellow]Tip:[/yellow] run "
            "[bold]primocut models --tools[/bold] to see OpenRouter models that "
            "support tools."
        )
        raise typer.Exit(code=1)

    console.print(f"[green]Report generated:[/green] {result}")


@app.command()
def models(
    free: bool = typer.Option(False, "--free", help="Free models only"),
    tools: bool = typer.Option(True, "--tools/--all", help="Only models that support tools"),
    limit: int = typer.Option(40, "--limit", help="Maximum number of rows to show"),
) -> None:
    """List OpenRouter models (by default, those that support tool use)."""
    setup_logging()
    from .openrouter import fetch_models, filter_models

    try:
        raw = fetch_models()
    except Exception as exc:  # network/API
        console.print(f"[red]Could not query OpenRouter:[/red] {exc}")
        raise typer.Exit(code=1)

    rows = filter_models(raw, free_only=free, tools_only=tools)
    table = Table(title=f"OpenRouter — {len(rows)} model(s)"
                  + (" free" if free else "") + (" with tools" if tools else ""))
    table.add_column("Model (slug)", style="bold")
    table.add_column("Free")
    table.add_column("Tools")
    for r in rows[:limit]:
        table.add_row(r["id"], "✅" if r["free"] else "—", "✅" if r["tools"] else "—")
    console.print(table)
    if len(rows) > limit:
        console.print(f"[dim]… and {len(rows) - limit} more. Use --limit to see more.[/dim]")


@app.command()
def serve(
    host: str | None = typer.Option(None, "--host", help="Host (config default)"),
    port: int | None = typer.Option(None, "--port", help="Port (config default)"),
) -> None:
    """Start the API + Web UI (FastAPI/uvicorn)."""
    setup_logging()
    import uvicorn

    from .api.app import create_app
    from .db import get_database

    settings = get_settings()
    get_database(settings)  # ensure schema/migrations
    console.print(
        f"[green]PRIMOCUT[/green] at http://{host or settings.serve_host}:{port or settings.serve_port}"
    )
    uvicorn.run(create_app(), host=host or settings.serve_host, port=port or settings.serve_port)


@app.command()
def worker() -> None:
    """Start an RQ worker to process the videos in the queue."""
    setup_logging()
    from redis import Redis
    from rq import Queue, Worker

    from .db import get_database

    settings = get_settings()
    get_database(settings)  # ensure schema/migrations
    conn = Redis.from_url(settings.redis_url)
    console.print(f"[green]Worker[/green] listening on queue '{settings.rq_queue}' at {settings.redis_url}")
    Worker([Queue(settings.rq_queue, connection=conn)], connection=conn).work()


